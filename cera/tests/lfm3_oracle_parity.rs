/// Relative difference, robust near zero.
fn rel_diff(a: f64, b: f64) -> f64 {
    (a - b).abs() / (a.abs() + b.abs() + 1e-9)
}

/// How closely a node's activation sum must track llama.cpp's.
struct NodeTolerance {
    /// Relative tolerance for sums of at least `large`.
    rel: f64,
    /// Looser tolerance between `floor` and `large`: those sums are differences of
    /// large positive and negative terms (the sandwich-normed residual stream
    /// cancels hard), so the same noise is a bigger fraction of the result.
    small_rel: f64,
    large: f64,
    /// Below this oracle magnitude a sum is dominated by cancellation, so its
    /// relative diff says nothing; such nodes are reported, not gated.
    floor: f64,
}

/// Real checkpoint on a Q8_0 file: sized for the accumulation-order and
/// activation-quantization noise between cera's and llama.cpp's CPU kernels.
const Q8_NODES: NodeTolerance = NodeTolerance {
    rel: 0.05,
    small_rel: 0.30,
    large: 100.0,
    floor: 10.0,
};

/// Synthetic f32 model: only summation order differs. Sums under 0.5 are a few
/// hundredths of cancellation residue over thousands of terms, so they are not
/// gated; the logits gate beside this one is tight (gap 0.002 on a spread of 2.4).
const F32_NODES: NodeTolerance = NodeTolerance {
    rel: 0.01,
    small_rel: 0.05,
    large: 2.0,
    floor: 0.5,
};

/// How closely cera's last-token logits must track a llama.cpp reference: of the
/// reference's top-k tokens, at least `min_overlap` must be in cera's top-k, and
/// each must be within `max_gap` in logit units (the scale differs per model; see
/// `MODEL_SETS`).
struct LogitTolerance {
    min_overlap: usize,
    max_gap: f64,
}

/// LFM3-1.7B, Q8_0 (logit spread ~2.6).
const Q8_TOLERANCE: LogitTolerance = LogitTolerance {
    min_overlap: 28,
    max_gap: 0.6,
};

/// LFM3-1.7B, bf16.
const BF16_TOLERANCE: LogitTolerance = LogitTolerance {
    min_overlap: 31,
    max_gap: 0.12,
};

/// Synthetic f32 model, whose logits are a few units wide: only summation order
/// differs from llama.cpp.
const F32_TOLERANCE: LogitTolerance = LogitTolerance {
    min_overlap: 32,
    max_gap: 0.01,
};

/// Each prompt's fixture JSON for a fixture set, in index order.
fn fixtures(set: &str) -> Vec<(String, serde_json::Value)> {
    let dir = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/oracle-lfm3")
        .join(set);
    let read = |p: PathBuf| -> serde_json::Value {
        serde_json::from_str(&std::fs::read_to_string(&p).expect("read fixture"))
            .unwrap_or_else(|e| panic!("parse {}: {e}", p.display()))
    };
    read(dir.join("index.json"))["prompts"]
        .as_array()
        .expect("prompts")
        .iter()
        .map(|entry| {
            let fname = entry["fixture"].as_str().expect("fixture").to_string();
            let fx = read(dir.join(&fname));
            (fname, fx)
        })
        .collect()
}

fn oracle_requested() -> bool {
    let on = std::env::var("CERA_ORACLE").as_deref() == Ok("1");
    if !on {
        eprintln!("skipping: CERA_ORACLE=1 not set");
    }
    on
}

fn load(path: &std::path::Path) -> (LfmModel, BpeTokenizer) {
    let tokenizer = BpeTokenizer::from_gguf(&GgufFile::open(path).expect("open gguf"))
        .expect("tokenizer from gguf");
    let model = LfmModel::from_gguf(GgufFile::open(path).expect("open gguf"), 8192)
        .expect("load lfm3 through LfmModel");
    (model, tokenizer)
}

fn fresh_state(model: &LfmModel) -> InferenceState {
    InferenceState::from_config_with_compression(model.config(), &KvCompression::None)
        .expect("inference state")
}

/// Feed `tokens` one at a time through the decode path, returning the last logits.
fn decode_all(model: &LfmModel, state: &mut InferenceState, tokens: &[u32]) -> Vec<f32> {
    tokens
        .iter()
        .map(|&t| model.forward(&[t], state.seq_len, state))
        .last()
        .expect("at least one token")
}

/// The llama.cpp op each recorded node maps to.
fn expected_op(name: &str) -> &'static str {
    match name {
        "model.embed_tokens" => "GET_ROWS",
        "result_norm" => "MUL",
        "result_output" => "MUL_MAT",
        n if n.starts_with("l_out-") => "ADD",
        n if n.starts_with("model.layers.{}.self_attn.gate-") => "SIGMOID",
        n if n.starts_with("model.layers.{}.") => "MUL",
        other => panic!("unmapped oracle node {other:?}"),
    }
}

/// Compare cera's last-token logits with a fixture's summary of llama.cpp's.
fn check_logits(
    fname: &str,
    got: &[f32],
    want: &serde_json::Value,
    tol: &LogitTolerance,
) -> Vec<String> {
    let want_top: Vec<(usize, f64)> = want["top"]
        .as_array()
        .expect("logits summary missing; regenerate with gen_logits_oracle.py")
        .iter()
        .map(|p| {
            (
                p[0].as_u64().expect("id") as usize,
                p[1].as_f64().expect("v"),
            )
        })
        .collect();
    let k = want_top.len();
    if let Some(at) = got.iter().position(|x| !x.is_finite()) {
        return vec![format!(
            "[{fname}] logits are not finite (first at index {at}: {})",
            got[at]
        )];
    }
    let mut order: Vec<usize> = (0..got.len()).collect();
    order.sort_by(|&a, &b| got[b].total_cmp(&got[a]));
    let got_top = &order[..k];

    let overlap = want_top
        .iter()
        .filter(|(id, _)| got_top.contains(id))
        .count();
    let worst = want_top
        .iter()
        .map(|&(id, v)| (got[id] as f64 - v).abs())
        .fold(0.0f64, |m, d| if d.is_nan() { f64::NAN } else { m.max(d) });
    let n = got.len() as f64;
    let mean = got.iter().map(|&x| x as f64).sum::<f64>() / n;
    let std = (got.iter().map(|&x| (x as f64 - mean).powi(2)).sum::<f64>() / n).sqrt();
    eprintln!(
        "[{fname}] logits: top1 cera={} llama={}, top-{k} overlap {overlap}, worst gap {worst:.3}, \
         mean {mean:.3} vs {:.3}, std {std:.3} vs {:.3}",
        got_top[0],
        want_top[0].0,
        want["mean"].as_f64().expect("mean"),
        want["std"].as_f64().expect("std"),
    );

    let mut problems = Vec::new();
    let got_top1_ref = want_top
        .iter()
        .find(|&&(id, _)| id == got_top[0])
        .map(|&(_, v)| v);
    if got_top[0] != want_top[0].0
        && got_top1_ref.is_none_or(|v| (want_top[0].1 - v).abs() > tol.max_gap)
    {
        problems.push(format!(
            "[{fname}] top-1 token differs: cera {} vs llama {}",
            got_top[0], want_top[0].0
        ));
    }
    if overlap < tol.min_overlap {
        problems.push(format!(
            "[{fname}] top-{k} overlap {overlap} < {}",
            tol.min_overlap
        ));
    }
    if worst.is_nan() || worst > tol.max_gap {
        problems.push(format!(
            "[{fname}] top-{k} logit gap {worst:.3} > {}",
            tol.max_gap
        ));
    }
    problems
}

/// Tokenizer parity: the model and llama.cpp must see the same prompt.
fn check_tokens(
    tokenizer: &BpeTokenizer,
    fname: &str,
    fx: &serde_json::Value,
) -> Result<Vec<u32>, String> {
    let want: Vec<u32> = fx["input_tokens"]
        .as_array()
        .expect("tokens")
        .iter()
        .map(|v| v.as_u64().expect("token") as u32)
        .collect();
    let got = tokenizer.encode(fx["prompt"].as_str().expect("prompt"));
    if got == want {
        Ok(got)
    } else {
        Err(format!(
            "[{fname}] tokenizer mismatch:\n    cera:  {got:?}\n    llama: {want:?}"
        ))
    }
}

/// Run `tokens` through the decode path with the oracle dump active, and compare
/// the recorded node sums with the fixture's llama.cpp ones. Returns the last
/// logits and any problems.
fn check_nodes(
    model: &LfmModel,
    tokens: &[u32],
    fname: &str,
    fx: &serde_json::Value,
    tol: &NodeTolerance,
) -> (Vec<f32>, Vec<String>) {
    let last = model.config().n_layers - 1;
    // llama.cpp prunes its graph to the last token after the last layer's
    // operator: those nodes (and the result_* ones) cover one position, every
    // other node covers all of them.
    let last_pos_only = |name: &str| {
        name.starts_with("result_")
            || name == format!("l_out-{last}")
            || name == format!("model.layers.{{}}.post_ffn_norm-{last}")
    };

    let mut state = fresh_state(model);
    oracle_dump::begin();
    let logits = decode_all(model, &mut state, tokens);
    let recorded = oracle_dump::take();

    let cera: HashMap<String, f64> =
        recorded
            .into_iter()
            .fold(HashMap::new(), |mut acc, (name, sum)| {
                if last_pos_only(&name) {
                    acc.insert(name, sum);
                } else {
                    *acc.entry(name).or_insert(0.0) += sum;
                }
                acc
            });
    let want: HashMap<(&str, &str), f64> = fx["nodes"]
        .as_array()
        .expect("nodes")
        .iter()
        .map(|n| {
            (
                (
                    n["name"].as_str().expect("name"),
                    n["op"].as_str().expect("op"),
                ),
                n["sum"].as_f64().expect("sum"),
            )
        })
        .collect();

    let mut nodes: Vec<_> = cera.iter().collect();
    nodes.sort_by(|a, b| a.0.cmp(b.0));
    let (checked, worst, mut problems) = nodes.into_iter().fold(
        (0usize, 0.0f64, Vec::new()),
        |(checked, worst, mut problems), (name, &got)| {
            let op = expected_op(name);
            let Some(&exp) = want.get(&(name.as_str(), op)) else {
                problems.push(format!("[{fname}] oracle has no node {name:?} ({op})"));
                return (checked, worst, problems);
            };
            let d = rel_diff(got, exp);
            // result_output sums ~1e5 partially cancelling logits: report only.
            if name == "result_output" || exp.abs() < tol.floor {
                eprintln!("[{fname}] (info) {name}/{op}: cera={got:.4} llama={exp:.4} rel={d:.4}");
                return (checked, worst, problems);
            }
            let limit = if exp.abs() >= tol.large {
                tol.rel
            } else {
                tol.small_rel
            };
            if d.is_nan() || d > limit {
                problems.push(format!(
                    "[{fname}] sum mismatch at {name}/{op}: cera={got:.4} llama={exp:.4} rel={d:.4}"
                ));
            }
            (checked + 1, worst.max(d), problems)
        },
    );
    // Per layer: operator_norm, post_operator_norm, post_ffn_norm and l_out, plus the
    // gate on attention layers. Every recorded hook must be present once per layer, so
    // losing a kind (or most of one) cannot hide behind the others still matching.
    let n_layers = model.config().n_layers;
    let n_attention = model
        .config()
        .block_types
        .iter()
        .filter(|b| **b == cera::model::BlockType::Attention)
        .count();
    for (prefix, expected) in [
        ("model.layers.{}.operator_norm-", n_layers),
        ("model.layers.{}.post_operator_norm-", n_layers),
        ("model.layers.{}.post_ffn_norm-", n_layers),
        ("l_out-", n_layers),
        ("model.layers.{}.self_attn.gate-", n_attention),
    ] {
        let recorded = cera.keys().filter(|k| k.starts_with(prefix)).count();
        if recorded != expected {
            problems.push(format!(
                "[{fname}] {recorded} {prefix}* hooks recorded, expected {expected}: hook drift"
            ));
        }
    }
    if checked < n_layers {
        problems.push(format!(
            "[{fname}] only {checked} nodes gated: hook/fixture drift"
        ));
    }
    eprintln!("[{fname}] {checked} gated node sums, worst rel diff {worst:.5}");
    (logits, problems)
}

/// The Q8_0 file of a set, or `None` when it is absent and the caller allows that.
/// `CERA_ORACLE=1` asked for coverage, so an absent file is only tolerated for sets
/// other than the first unless `CERA_REQUIRE_MODEL` is set.
fn model_path(set: &ModelSet, file: &str, required: bool) -> Option<PathBuf> {
    let path = common::models_dir().join(file);
    if path.exists() {
        return Some(path);
    }
    if let Some(dir) = set.convert_from.and_then(std::env::var_os) {
        eprintln!(
            "converting {} into {}",
            PathBuf::from(&dir).display(),
            path.display()
        );
        cera::convert::pipeline::quantize_safetensors_to_gguf(
            std::path::Path::new(&dir),
            &path,
            cera::convert::quantize::TargetQuant::Q8_0,
        )
        .expect("convert the checkpoint with cera::convert");
        return Some(path);
    }
    let strict = required || common::require_model();
    assert!(
        !strict,
        "CERA_ORACLE=1 but {} is absent; set CERA_ORACLE_MODELS_DIR (or CERA_LFM3_1_7B_HF \
         to convert it from a checkpoint)",
        path.display()
    );
    eprintln!(
        "NOT CHECKED: {} is absent, so set {} did not run",
        path.display(),
        set.fixtures
    );
    None
}

#[test]
#[ignore] // run with --ignored + CERA_ORACLE=1
fn lfm3_matches_llama_cpp_oracle() {
    if !oracle_requested() {
        return;
    }
    let mut failures = Vec::new();
    for (i, set) in MODEL_SETS.iter().enumerate() {
        let Some(path) = model_path(set, set.q8_file, i == 0) else {
            continue;
        };
        let (model, tokenizer) = load(&path);
        for (fname, fx) in fixtures(set.fixtures) {
            let fname = format!("{}/{fname}", set.fixtures);
            match check_tokens(&tokenizer, &fname, &fx) {
                Err(e) => failures.push(e),
                Ok(tokens) => {
                    let (logits, problems) = check_nodes(&model, &tokens, &fname, &fx, &Q8_NODES);
                    failures.extend(problems);
                    failures.extend(check_logits(&fname, &logits, &fx["logits"], &set.q8));
                }
            }
        }
    }

    assert!(
        failures.is_empty(),
        "lfm3 diverges from llama.cpp:\n{}",
        failures.join("\n")
    );
}

/// The tight gate: with bf16 weights nothing is quantized, so any disagreement is
/// the graph (a norm, the gate, a rope base or mask, the window), not noise.
#[test]
#[ignore] // run with --ignored + CERA_ORACLE=1
fn lfm3_bf16_logits_match_llama_cpp() {
    if !oracle_requested() {
        return;
    }
    let mut failures = Vec::new();
    for set in MODEL_SETS {
        // the bf16 files are big and optional: absence is reported, not fatal
        let Some(bf16_file) = set.bf16_file else {
            continue;
        };
        let path = common::models_dir().join(bf16_file);
        if !path.exists() {
            eprintln!(
                "NOT CHECKED: {} is absent, so the tight bf16 gate did not run for {}",
                path.display(),
                set.fixtures
            );
            continue;
        }
        let (model, tokenizer) = load(&path);
        for (fname, fx) in fixtures(set.fixtures) {
            let fname = format!("{}/{fname}", set.fixtures);
            match check_tokens(&tokenizer, &fname, &fx) {
                Err(e) => failures.push(e),
                Ok(tokens) => {
                    let mut state = fresh_state(&model);
                    let logits = decode_all(&model, &mut state, &tokens);
                    failures.extend(check_logits(&fname, &logits, &fx["logits_bf16"], &set.bf16));
                }
            }
        }
    }

    assert!(
        failures.is_empty(),
        "lfm3 (bf16) diverges from llama.cpp:\n{}",
        failures.join("\n")
    );
}

/// Batched prefill must agree with token-by-token decode: same KV, same logits.
/// The prefill loop re-implements the sandwich norms around a per-token attention
/// fallback and has its own multi-tap conv, so this is the check that those copies
/// of the graph stay one.
#[test]
#[ignore] // real 1.7B checkpoints in a debug build take 20+ minutes: --ignored + CERA_ORACLE=1
fn lfm3_prefill_matches_decode() {
    if !oracle_requested() {
        return;
    }
    // `model_path`, not `fixture_or_skip`: a set whose GGUF is converted on demand must not
    // depend on the sibling oracle test having run first
    for (i, set) in MODEL_SETS.iter().enumerate() {
        if let Some(path) = model_path(set, set.q8_file, i == 0) {
            prefill_matches_decode(&path);
        }
    }
}

fn prefill_matches_decode(path: &std::path::Path) {
    let (model, tokenizer) = load(path);

    // Long enough to cross the 256-token window and to take the batched conv path.
    let prompt = (0..60)
        .map(|i| format!("Entry {i}: the fox number {} crossed the river.", i * 7 + 3))
        .collect::<Vec<_>>()
        .join("\n");
    let tokens = tokenizer.encode(&prompt);
    assert!(tokens.len() > 300, "prompt must outgrow the window");

    let mut decode_state = fresh_state(&model);
    let decode_logits = decode_all(&model, &mut decode_state, &tokens);

    let mut prefill_state = fresh_state(&model);
    let prefill_logits = model.forward_prefill(&tokens, 0, &mut prefill_state);

    assert_eq!(prefill_state.seq_len, decode_state.seq_len);
    assert_eq!(argmax(&prefill_logits), argmax(&decode_logits));
    let (dot, na, nb) = prefill_logits.iter().zip(&decode_logits).fold(
        (0.0f64, 0.0f64, 0.0f64),
        |(dot, na, nb), (&a, &b)| {
            (
                dot + a as f64 * b as f64,
                na + (a as f64).powi(2),
                nb + (b as f64).powi(2),
            )
        },
    );
    let cosine = dot / (na.sqrt() * nb.sqrt());
    assert!(cosine > 0.999, "prefill vs decode logits cosine {cosine}");

    // Both paths must leave a state that continues identically.
    let next = argmax(&decode_logits);
    let a = model.forward(&[next], decode_state.seq_len, &mut decode_state);
    let b = model.forward(&[next], prefill_state.seq_len, &mut prefill_state);
    assert_eq!(argmax(&a), argmax(&b));
}

// ---- synthetic model: runs without the real weights -------------------------

/// A generated test GGUF that deletes itself.
struct TempModel(PathBuf);

impl Drop for TempModel {
    fn drop(&mut self) {
        let _ = std::fs::remove_file(&self.0);
    }
}

/// Generate the tiny synthetic `lfm3` GGUF with the python script, or `None` (and
/// a loud note) when python lacks `numpy`/`gguf`. `CERA_REQUIRE_ORACLE=1` turns
/// that skip into a failure, as does a failed generation.
fn synthetic_model(q8_0: bool) -> Option<TempModel> {
    let strict = std::env::var("CERA_REQUIRE_ORACLE").as_deref() == Ok("1");
    let script = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../scripts/oracle/create_lfm3_test_model.py");
    assert!(script.exists(), "missing {}", script.display());

    let has_deps = std::process::Command::new("python3")
        .args(["-c", "import numpy, gguf"])
        .output()
        .is_ok_and(|o| o.status.success());
    if !has_deps {
        assert!(
            !strict,
            "python3 lacks numpy/gguf and CERA_REQUIRE_ORACLE=1"
        );
        eprintln!("skipping: python3 lacks numpy/gguf for the synthetic lfm3 model");
        return None;
    }

    // Tests run in parallel and each deletes its file on drop, so no two share a name.
    static NEXT: std::sync::atomic::AtomicUsize = std::sync::atomic::AtomicUsize::new(0);
    let variant = if q8_0 { "q8" } else { "f32" };
    let out = std::env::temp_dir().join(format!(
        "test_lfm3_{variant}_{}_{}.gguf",
        std::process::id(),
        NEXT.fetch_add(1, std::sync::atomic::Ordering::Relaxed)
    ));
    // owns the path before python writes it, so a failed run leaves nothing behind
    let model = TempModel(out);
    let mut cmd = std::process::Command::new("python3");
    cmd.arg(&script).arg(&model.0);
    if q8_0 {
        cmd.arg("--q8_0");
    }
    let status = cmd.status().expect("run python3");
    assert!(
        status.success(),
        "generating the synthetic lfm3 model failed"
    );
    Some(model)
}

/// The tiny model against llama.cpp at f32: nothing is quantized, so every node
/// sum and the logits must agree to summation-order noise. Each of `lfm3`'s
/// differences from `lfm2` (7-tap conv, sandwich norms, attention gate, sliding
/// window, per-layer rope base, partial rotary, untied output) moves these.
#[test]
fn lfm3_synthetic_matches_llama_cpp() {
    let Some(model_file) = synthetic_model(false) else {
        return;
    };
    let (model, tokenizer) = load(&model_file.0);

    let failures: Vec<String> = fixtures("synthetic")
        .into_iter()
        .flat_map(|(fname, fx)| match check_tokens(&tokenizer, &fname, &fx) {
            Err(e) => vec![e],
            Ok(tokens) => {
                let (logits, mut problems) = check_nodes(&model, &tokens, &fname, &fx, &F32_NODES);
                problems.extend(check_logits(&fname, &logits, &fx["logits"], &F32_TOLERANCE));
                problems
            }
        })
        .collect();

    assert!(
        failures.is_empty(),
        "synthetic lfm3 diverges from llama.cpp:\n{}",
        failures.join("\n")
    );
}

/// Largest absolute difference, relative to the reference's largest magnitude. NaN when
/// either side holds a NaN or infinity (so a `<=` gate fails on it); the lengths must match.
fn rel_max_diff(got: &[f32], want: &[f32]) -> f32 {
    assert_eq!(got.len(), want.len(), "compared slices differ in length");
    let mut scale = 0.0f32;
    let mut worst = 0.0f32;
    for (&a, &b) in got.iter().zip(want) {
        if !a.is_finite() || !b.is_finite() {
            return f32::NAN;
        }
        scale = scale.max(b.abs());
        worst = worst.max((a - b).abs());
    }
    worst / (scale + 1e-9)
}

/// Prefill must leave the state, and the logits, that decode does: bit for bit on
/// aarch64 without BLAS (the arithmetic decode and the batched kernels were made to
/// share), closely elsewhere. The Q8_0 file takes the batched-GEMM prefill, where the
/// multi-tap conv and the `lfm3` post-norms live; the f32 file takes the per-token
/// fallback. The prompt is longer than the 4-token window.
#[test]
fn lfm3_synthetic_prefill_matches_decode() {
    let exact = cfg!(all(target_arch = "aarch64", not(has_blas)));
    for q8_0 in [false, true] {
        let Some(model_file) = synthetic_model(q8_0) else {
            return;
        };
        let (model, tokenizer) = load(&model_file.0);
        let tokens = tokenizer.encode("Helloworld12345");
        // the generator's sliding window is 4; the prompt must outgrow it by a margin
        const SYNTHETIC_WINDOW: usize = 4;
        assert!(
            tokens.len() > SYNTHETIC_WINDOW * 3,
            "prompt must outgrow the window"
        );
        let label = if q8_0 { "q8_0" } else { "f32" };

        let mut decode_state = fresh_state(&model);
        let decode_logits = decode_all(&model, &mut decode_state, &tokens);
        let mut prefill_state = fresh_state(&model);
        let prefill_logits = model.forward_prefill(&tokens, 0, &mut prefill_state);
        assert_eq!(prefill_state.seq_len, tokens.len(), "{label}");

        let (state_limit, logit_limit) = if exact {
            (0.0, 0.0)
        } else if cfg!(has_blas) && q8_0 {
            (0.15, 0.10)
        } else {
            (1e-3, 1e-3)
        };
        decode_state
            .layers
            .iter()
            .zip(&prefill_state.layers)
            .enumerate()
            .for_each(|(layer, pair)| {
                let diff = match pair {
                    (
                        LayerState::Conv { buffer: want, .. },
                        LayerState::Conv { buffer: got, .. },
                    ) => rel_max_diff(got, want),
                    (
                        LayerState::Attention {
                            key_cache: want_k,
                            value_cache: want_v,
                            ..
                        },
                        LayerState::Attention {
                            key_cache: got_k,
                            value_cache: got_v,
                            ..
                        },
                    ) => rel_max_diff(got_k, want_k).max(rel_max_diff(got_v, want_v)),
                    _ => panic!("{label}: layer {layer} kinds differ"),
                };
                eprintln!("[synthetic {label}] layer {layer} state rel diff {diff:e}");
                assert!(
                    diff <= state_limit,
                    "{label}: layer {layer} state differs by {diff}"
                );
            });

        let logit_diff = rel_max_diff(&prefill_logits, &decode_logits);
        assert!(
            logit_diff <= logit_limit,
            "{label}: logits differ by {logit_diff}"
        );
        assert_eq!(argmax(&prefill_logits), argmax(&decode_logits), "{label}");

        // The two states must continue identically.
        let next = argmax(&decode_logits);
        let a = model.forward(&[next], decode_state.seq_len, &mut decode_state);
        let b = model.forward(&[next], prefill_state.seq_len, &mut prefill_state);
        assert_eq!(argmax(&a), argmax(&b), "{label}: next step");
    }
}

/// What `lfm3` cannot honour it must not run: a TurboQuant request falls back to the
/// uncompressed cache (the compressed read would skip the sliding-window mask; the
/// allocator and `resolved_for` agree, and `kv_cache` has a python-free unit test for
/// the rule), while LoRA (no validated hooks around the sandwich norms and gate) and
/// the `n_keep` shift (one RoPE schedule) are refused.
#[test]
fn lfm3_refuses_what_it_cannot_honour() {
    let Some(model_file) = synthetic_model(false) else {
        return;
    };
    let (model, _) = load(&model_file.0);

    assert!(!model.supports_lora());
    assert!(!model.supports_kv_shift());
    assert!(!model.turboquant_supported());

    let tq = KvCompression::TurboQuant {
        seed: 1,
        keys: true,
        values: true,
    };
    // The request is not an error (the trait contract): it resolves to the plain cache,
    // through the allocator too, so a state built directly cannot be compressed either.
    model
        .configure_kv_compression(&tq)
        .expect("an unservable TurboQuant request falls back instead of failing");
    assert_eq!(tq.resolved_for(model.config()).cache_tag(), "");
    let state = InferenceState::from_config_with_compression(model.config(), &tq).unwrap();
    assert!(
        state.layers.iter().all(|l| match l {
            LayerState::Attention {
                compressed_keys,
                compressed_values,
                ..
            } => compressed_keys.is_none() && compressed_values.is_none(),
            _ => true,
        }),
        "an lfm3 state must not hold a TurboQuant cache"
    );
    model
        .configure_kv_compression(&KvCompression::None)
        .expect("uncompressed KV is supported");
}

// ── The comparison gates themselves ─────────────────────────────────────────
// These run without a model: a gate that cannot fail on NaN is a gate that passes a model
// whose state or logits are all NaN (argmax of an all-NaN row is 0 on both sides).

#[test]
fn rel_max_diff_fails_on_nan_and_on_length_mismatch() {
    assert_eq!(rel_max_diff(&[1.0, 2.0], &[1.0, 2.0]), 0.0);
    assert!(rel_max_diff(&[1.0, 2.5], &[1.0, 2.0]) > 0.0);
    assert!(rel_max_diff(&[f32::NAN, 2.0], &[1.0, 2.0]).is_nan());
    assert!(rel_max_diff(&[1.0, 2.0], &[1.0, f32::NAN]).is_nan());
    assert!(rel_max_diff(&[f32::NAN], &[f32::NAN]).is_nan());
    assert!(rel_max_diff(&[f32::INFINITY], &[f32::INFINITY]).is_nan());
    // and a NaN diff is unordered, so no `<=` gate can pass it
    assert!(
        rel_max_diff(&[f32::NAN], &[1.0])
            .partial_cmp(&0.0)
            .is_none()
    );
    assert!(std::panic::catch_unwind(|| rel_max_diff(&[1.0], &[1.0, 2.0])).is_err());
}

#[test]
fn check_logits_reports_non_finite_logits() {
    let want = serde_json::json!({"top": [[1, 5.0], [0, 4.0]], "mean": 0.0, "std": 1.0});
    let tol = LogitTolerance {
        min_overlap: 2,
        max_gap: 1.0,
    };
    assert!(check_logits("ok", &[4.0, 5.0, 0.0], &want, &tol).is_empty());
    for bad in [
        vec![f32::NAN; 3],
        vec![4.0, f32::NAN, 0.0],
        vec![4.0, 5.0, f32::INFINITY],
    ] {
        let problems = check_logits("nan", &bad, &want, &tol);
        assert!(!problems.is_empty(), "{bad:?} passed the logit gate");
    }
}
