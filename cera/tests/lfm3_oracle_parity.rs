//! LFM3 (`lfm3` arch) against llama.cpp, plus the prefill/decode identity that
//! needs no reference binary.
//!
//! `lfm3` is `lfm2` plus sandwich norms, a per-head sigmoid gate on the attention
//! output, per-layer sliding windows, and partial rotary on the global layers.
//! Each of those is a place a wrong implementation still produces fluent text, so
//! the gates here are numeric, not "does it generate".
//!
//! Fixtures under `tests/fixtures/oracle-lfm3/<set>/` come from llama.cpp on the
//! same GGUF (see `scripts/oracle/`): `nodes` are `llama-eval-callback` activation
//! sums, `logits` / `logits_bf16` summarize the last token's logits from the
//! quantized file and from a bf16 conversion. `index.json` names the `model_file`,
//! resolved under `CERA_ORACLE_MODELS_DIR` (default `target/oracle/models`). One
//! prompt is longer than the model's 256-token window, so the sliding-window mask
//! and the long-range rotary schedule both matter.
//!
//! Why two logits tiers. Both implementations quantize activations to Q8_0 on a
//! Q8_0 file, and on some prompts that noise is large (llama.cpp itself is 4% off
//! its own bf16 logits on `1 + 2 + 3 =`), so the Q8_0 gate is only a smoke check.
//! The bf16 file has no activation quantization: cera matches llama.cpp there to
//! ~1e-3 relative L2, which is what actually pins the graph.
//!
//! The `synthetic` fixture set needs no real weights: a tiny random `lfm3` GGUF is
//! generated by `scripts/oracle/create_lfm3_test_model.py` (deterministic, f32) and
//! compared with committed llama.cpp reference values at tight tolerance, so the
//! graph is checked wherever python has `numpy` and `gguf`. The CI workflows do not
//! install them, so there these tests print "skipping" and pass; set
//! `CERA_REQUIRE_ORACLE=1` to make a missing dependency a failure.
//!
//! Tests:
//!   * `lfm3_synthetic_matches_llama_cpp` / `lfm3_synthetic_prefill_matches_decode`:
//!     the synthetic pair described above (the second also on a Q8_0 variant).
//!   * `lfm3_refuses_what_it_cannot_honour`: the TurboQuant fallback, and the LoRA and
//!     `n_keep` refusals, on the synthetic model (the TurboQuant rule itself also has a
//!     python-free unit test in `kv_cache`).
//!   * `lfm3_matches_llama_cpp_oracle`: node sums + Q8_0 logits. Opt-in
//!     (`CERA_ORACLE=1`, `--ignored`); an absent GGUF of the first model set is a hard
//!     failure (every set with `CERA_REQUIRE_MODEL`), since the caller asked for coverage.
//!   * `lfm3_bf16_logits_match_llama_cpp`: the tight bf16 gate. Same opt-in; the
//!     4 GB bf16 file is optional and its absence is reported, not fatal.
//!   * `lfm3_prefill_matches_decode`: needs only the Q8_0 GGUF; opt-in like the
//!     two above (`CERA_ORACLE=1`, `--ignored`, since a debug build over the real
//!     checkpoints takes 20+ minutes); skips when the GGUF is absent unless
//!     `CERA_REQUIRE_MODEL` is set.
//!
//! Run:
//!   CERA_ORACLE=1 CERA_ORACLE_MODELS_DIR=~/.leap/models \
//!     cargo test -p cera --release --test lfm3_oracle_parity -- --ignored --nocapture

