#!/usr/bin/env python3
"""Slang (SPIR-V passthrough) variants of the tiled causal prefill attention, `attention_prefill_hd64.wgsl`,
with fp16 math. A research tool: `cera/examples/wgpu_attn_bench.rs` times them against the f32 kernel and
measures their error against an f64 reference.

The structure is the WGSL kernel's: a workgroup of 128 threads (8 query groups x 16 columns) owns 32 queries
of one head and sweeps the keys 32 at a time. What changes is the precision: Q (pre-scaled by
scale * log2(e)), K^T, V and the probabilities live in shared memory as half, S = QK^T and the PV partial
sums are accumulated in half, and the softmax statistics and the output accumulator stay f32.

Two knobs say how often a half partial sum is widened to f32 and added to an f32 accumulator, which bounds
the rounding error of a long half sum:
  S_BLOCK: QK^T over 64 dims, widened every S_BLOCK dims (64, 32, 16 or 8).
  PV_BLOCK: P V over a 32-key tile, widened every PV_BLOCK keys (32, 16, 8 or 4).

Usage: python3 scripts/attn-fp16/gen.py OUT_DIR   (writes attn_f16_s{S}_p{P}.slang and compiles with slangc)
"""
import os
import shutil
